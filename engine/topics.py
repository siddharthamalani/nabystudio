#!/usr/bin/env python3
"""Topic backlog: score, de-duplicate, rotate series.  python3 engine/topics.py  -> topics/backlog.md

Score (0-100) = weighted 1-5 ratings: audience 25%, curiosity 25%, uniqueness 20%, visual 15%, feasibility 15%.
(audience = matches what our data says works: what your own analytics say works for your audience.)
Duplicate check against topics/catalogue.json (everything already made) and the rest of the backlog:
  shared subject keywords -> DUPLICATE (don't make) or NEW ANGLE (allowed only if the 'angle' says what's different).
Series rotation: the next pick should not repeat the last episode's series."""
import json, os, difflib

STUDIO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = {"audience": .25, "curiosity": .25, "uniqueness": .20, "visual": .15, "feasibility": .15}


def score(t):
    return round(sum(W[k] * t["scores"].get(k, 3) for k in W) / 5 * 100)


def overlap(a, b):
    ka, kb = set(k.lower() for k in a["keys"]), set(k.lower() for k in b["keys"])
    shared = ka & kb
    sim = difflib.SequenceMatcher(None, a["title"].lower(), b["title"].lower()).ratio()
    return shared, sim


def main():
    cat = json.load(open(os.path.join(STUDIO, "topics", "catalogue.json")))
    bl = json.load(open(os.path.join(STUDIO, "topics", "backlog.json")))
    last_series = "Series One"   # EpN
    rows = []
    for t in bl:
        flags = []
        for c in cat:
            shared, sim = overlap(t, c)
            if len(shared) >= 2 or sim > .6:
                flags.append(("DUPLICATE of %s" if t["scores"].get("uniqueness", 3) <= 2 else "NEW ANGLE on %s") % c["ep"])
            elif shared:
                flags.append("touches %s (%s)" % (c["ep"], ", ".join(sorted(shared))))
        for u in bl:
            if u is t: continue
            shared, sim = overlap(t, u)
            if len(shared) >= 2: flags.append("overlaps backlog: %s" % u["subject"])
        s = score(t) - (40 if any(f.startswith("DUPLICATE") for f in flags) else 0)
        rows.append((s, t, flags))
    rows.sort(key=lambda r: -r[0])
    out = ["# Topic backlog (auto-generated by engine/topics.py: edit topics/backlog.json, not this file)", "",
           "Score = audience 25% · curiosity 25% · uniqueness 20% · visual 15% · feasibility 15%. Duplicates of made episodes lose 40.", "",
           "| Rank | Score | Series | Title | Subject | Flags |", "|---|---|---|---|---|---|"]
    for i, (s, t, f) in enumerate(rows, 1):
        nxt = " ⭐ next pick" if i == 1 or (t["series"] != last_series and all(r[1]["series"] == last_series for r in rows[:i - 1])) else ""
        out.append("| %d | %d | %s | %s%s | %s | %s |" % (i, s, t["series"], t["title"], nxt, t["subject"], "; ".join(f) or "clear"))
    out += ["", "Series rotation: last episode was **%s**, so prefer a different series next." % last_series]
    open(os.path.join(STUDIO, "topics", "backlog.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
